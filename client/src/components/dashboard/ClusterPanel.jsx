import React, { useState } from 'react';
import { 
  ShieldAlert, 
  MapPin, 
  Clock, 
  Layers, 
  Sliders, 
  ChevronRight, 
  ExternalLink, 
  AlertCircle,
  HelpCircle,
  CheckCircle2,
  SlidersHorizontal
} from 'lucide-react';

export default function ClusterPanel({
  clusters = [],
  thresholds = {},
  onUpdateThresholds,
  onInspectClusterOnMap,
  reportsWithoutCoordinatesCount = 0
}) {
  const [showThresholdConfig, setShowThresholdConfig] = useState(false);

  return (
    <div className="bg-white rounded-xl border border-gray-200 shadow-sm overflow-hidden">
      {/* Panel Header */}
      <div className="p-4 bg-gradient-to-r from-amber-50 to-orange-50 border-b border-amber-200 flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center space-x-2.5">
          <div className="p-2 bg-amber-500 text-white rounded-lg shadow-sm">
            <ShieldAlert size={20} />
          </div>
          <div>
            <div className="flex items-center space-x-2">
              <h3 className="font-bold text-gray-900 text-base">
                Possible Incident Clusters
              </h3>
              <span className="bg-amber-200 text-amber-900 text-xs font-bold px-2 py-0.5 rounded-full">
                {clusters.length} Detected
              </span>
            </div>
            <p className="text-xs text-amber-800">
              Heuristic grouping of spatially and temporally correlated incident reports
            </p>
          </div>
        </div>

        {/* Threshold Adjustment Toggle */}
        <button
          onClick={() => setShowThresholdConfig(!showThresholdConfig)}
          className="flex items-center space-x-1.5 text-xs font-bold text-amber-900 bg-amber-100 hover:bg-amber-200 border border-amber-300 px-3 py-1.5 rounded-lg transition-colors"
        >
          <SlidersHorizontal size={14} />
          <span>{showThresholdConfig ? 'Hide Thresholds' : 'Configure Rules'}</span>
        </button>
      </div>

      {/* Safety & Compliance Policy Banner */}
      <div className="bg-amber-50/70 border-b border-amber-100 px-4 py-2 text-xs text-amber-900 flex items-start space-x-2">
        <AlertCircle size={15} className="text-amber-700 flex-shrink-0 mt-0.5" />
        <div className="space-y-0.5">
          <p className="font-medium">
            <strong>Rule-based grouping policy:</strong> Clusters are generated by deterministic proximity and time windows. 
            They do <em>not</em> represent official warnings, confirmed disasters, or AI predictions.
          </p>
        </div>
      </div>

      {/* Configurable Rules Drawer */}
      {showThresholdConfig && (
        <div className="p-4 bg-gray-50 border-b border-gray-200 text-xs space-y-3">
          <div className="font-bold text-gray-800 flex items-center justify-between">
            <span>Adjust Provisional Clustering Thresholds</span>
            <span className="text-gray-500 font-normal">Deterministic Haversine Heuristics</span>
          </div>
          
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
            <div>
              <label className="block text-gray-600 font-medium mb-1">
                Max Proximity Distance: <strong>{thresholds.maxDistanceKm || 8} km</strong>
              </label>
              <input
                type="range"
                min="2"
                max="20"
                step="1"
                value={thresholds.maxDistanceKm || 8}
                onChange={(e) => onUpdateThresholds && onUpdateThresholds({ maxDistanceKm: Number(e.target.value) })}
                className="w-full accent-amber-600 cursor-pointer"
              />
              <div className="flex justify-between text-[10px] text-gray-400">
                <span>2 km (Local)</span>
                <span>8 km (Default)</span>
                <span>20 km (Regional)</span>
              </div>
            </div>

            <div>
              <label className="block text-gray-600 font-medium mb-1">
                Time Window: <strong>{thresholds.timeWindowHours || 24} hours</strong>
              </label>
              <select
                value={thresholds.timeWindowHours || 24}
                onChange={(e) => onUpdateThresholds && onUpdateThresholds({ timeWindowHours: Number(e.target.value) })}
                className="w-full p-1.5 border border-gray-300 rounded bg-white text-xs"
              >
                <option value="6">6 Hours (Flash Floods)</option>
                <option value="12">12 Hours (Storm Events)</option>
                <option value="24">24 Hours (Standard Window)</option>
                <option value="48">48 Hours (Multi-Day Monsoon)</option>
              </select>
            </div>

            <div>
              <label className="block text-gray-600 font-medium mb-1">
                Category Grouping
              </label>
              <label className="flex items-center space-x-2 mt-2 cursor-pointer">
                <input
                  type="checkbox"
                  checked={thresholds.requireCategoryMatch || false}
                  onChange={(e) => onUpdateThresholds && onUpdateThresholds({ requireCategoryMatch: e.target.checked })}
                  className="rounded text-amber-600 focus:ring-0"
                />
                <span className="text-xs text-gray-700">Strict same-category match only</span>
              </label>
            </div>
          </div>
        </div>
      )}

      {/* Cluster List Feed */}
      <div className="divide-y divide-gray-100">
        {clusters.length === 0 ? (
          <div className="p-8 text-center text-gray-500">
            <CheckCircle2 size={36} className="mx-auto text-emerald-500 mb-2" />
            <h4 className="font-bold text-gray-800">No Dense Incident Clusters Detected</h4>
            <p className="text-xs text-gray-500 max-w-md mx-auto mt-1">
              Active incident reports are either spatially isolated or spread across longer time intervals.
            </p>
          </div>
        ) : (
          clusters.map(cluster => (
            <div key={cluster.clusterId} className="p-4 hover:bg-amber-50/20 transition-colors">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                <div className="space-y-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-black bg-amber-100 text-amber-900 border border-amber-300">
                      Possible cluster — requires review
                    </span>
                    <span className="font-mono text-xs text-gray-500 font-bold">
                      {cluster.clusterId}
                    </span>
                    <span className="bg-red-100 text-red-800 text-[10px] font-bold px-2 py-0.2 rounded-full">
                      {cluster.reportCount} Distinct Reports
                    </span>
                  </div>

                  <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-gray-600 pt-1">
                    <span className="flex items-center space-x-1">
                      <MapPin size={13} className="text-gray-400" />
                      <strong className="text-gray-800">
                        {cluster.locationEstimate.suco 
                          ? `${cluster.locationEstimate.suco}, ${cluster.locationEstimate.municipality}`
                          : cluster.locationEstimate.municipality}
                      </strong>
                    </span>

                    <span className="flex items-center space-x-1">
                      <Clock size={13} className="text-gray-400" />
                      <span>Span: {cluster.timeRange.spanHours} hrs</span>
                    </span>

                    <span className="flex items-center space-x-1">
                      <Layers size={13} className="text-gray-400" />
                      <span>Types: <strong>{cluster.categories.join(', ')}</strong></span>
                    </span>
                  </div>
                </div>

                {/* Inspect Action */}
                <button
                  onClick={() => onInspectClusterOnMap && onInspectClusterOnMap(cluster)}
                  className="flex items-center justify-center space-x-1 px-3 py-1.5 bg-brand-navy hover:bg-opacity-90 text-white rounded-lg text-xs font-bold shadow-sm whitespace-nowrap self-start sm:self-center"
                >
                  <span>Inspect on Map</span>
                  <ExternalLink size={13} />
                </button>
              </div>

              {/* Contributing Reports Chips */}
              <div className="mt-2.5 pt-2 border-t border-gray-100 flex flex-wrap items-center gap-1.5 text-xs">
                <span className="text-gray-400 text-[11px] font-medium mr-1">Contributing Reports:</span>
                {cluster.reports.map(r => (
                  <span 
                    key={r.client_id || r.id}
                    className="inline-flex items-center space-x-1 bg-gray-100 hover:bg-gray-200 border border-gray-200 px-2 py-0.5 rounded text-[11px] font-mono text-gray-700"
                  >
                    <span>{r.client_id}</span>
                    <span className="text-[9px] text-gray-400">({r.type})</span>
                  </span>
                ))}
                
                <span className="text-[10px] text-amber-700 ml-auto font-medium">
                  {cluster.verifiedCount} verified / {cluster.unverifiedCount} unverified
                </span>
              </div>
            </div>
          ))
        )}
      </div>

      {/* Missing coordinates notice */}
      {reportsWithoutCoordinatesCount > 0 && (
        <div className="bg-gray-50 border-t border-gray-200 p-3 text-xs text-gray-500 flex items-center justify-between">
          <span className="flex items-center space-x-1.5">
            <HelpCircle size={14} className="text-gray-400" />
            <span>
              {reportsWithoutCoordinatesCount} reports lack direct GPS coordinates and are excluded from spatial clusters (kept visible in administrative list).
            </span>
          </span>
          <span className="font-mono text-[10px] text-gray-400">SAFE FALLBACK</span>
        </div>
      )}
    </div>
  );
}
